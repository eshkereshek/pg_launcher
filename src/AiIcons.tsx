interface GlyphProps {
  name: string
  size?: number
  className?: string
}

export const PixelGlyph: React.FC<GlyphProps> = ({ name, size = 14, className }) => {
  const rows = GLYPHS[name] || GLYPHS.other
  return (
    <svg
      width={size}
      height={size}
      viewBox='0 0 8 8'
      shapeRendering='crispEdges'
      fill='currentColor'
      className={className}
      aria-hidden='true'
      focusable='false'
    >
      {rows.map((row, y) =>
        row.split('').map((cell, x) =>
          cell === '#' ? <rect key={`${x}-${y}`} x={x} y={y} width={1} height={1} /> : null,
        ),
      )}
    </svg>
  )
}

export const GroupIcon: React.FC<{ group: string; size?: number }> = ({ group, size = 13 }) => (
  <PixelGlyph name={group} size={size} />
)
