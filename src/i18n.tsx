interface LanguageContextType {
  language: Language;
  setLanguage: (lang: Language) => void;
  /** t('mods.byAuthor', { author: 'Modrinth' }) — подставляет {author} в строку. */
  t: (key: keyof Translations, params?: TranslateParams) => string;
}

/**
 * Язык вне React-дерева: форматирование чисел и дат живёт в утилитах
 * (projectMeta), которым нужен актуальный локаль, но нет доступа к хуку.
 */
let runtimeLanguage: Language = 'ru';

export const setRuntimeLanguage = (lang: Language) => {
  runtimeLanguage = lang;
};

export const getRuntimeLanguage = (): Language => runtimeLanguage;

/** Локаль для Intl: 'ru-RU' / 'en-US'. */
export const getLocale = (): string => (runtimeLanguage === 'en' ? 'en-US' : 'ru-RU');

export const interpolate = (text: string, params?: TranslateParams) => {
  if (!params || !text) return text;
  return text.replace(/\{(\w+)\}/g, (whole, name: string) =>
    Object.prototype.hasOwnProperty.call(params, name) ? String(params[name]) : whole
  );
};

/**
 * Перевод вне React-дерева: модульные хелперы и колбэки, куда не доходит
 * хук useTranslation, берут строку по текущему языку отсюда.
 */
export const translate = (key: keyof Translations, params?: TranslateParams): string =>
  interpolate(translations[runtimeLanguage][key] || translations.ru[key] || key, params);

export const LanguageContext = createContext<LanguageContextType>({
  language: 'ru',
  setLanguage: () => {},
  t: (key) => translations.ru[key]
});

export const LanguageProvider: React.FC<{ children: React.ReactNode }> = ({ children }) => {
  const [language, setLanguage] = useState<Language>('ru');

  useEffect(() => {
    const saved = localStorage.getItem('mc_launcher_lang') as Language;
    if (saved && (saved === 'ru' || saved === 'en')) {
      setLanguage(saved);
    }
  }, []);

  // Утилиты вне контекста (Intl-форматирование) читают язык отсюда.
  useEffect(() => {
    setRuntimeLanguage(language);
  }, [language]);

  const handleSetLanguage = (lang: Language) => {
    setLanguage(lang);
    localStorage.setItem('mc_launcher_lang', lang);
  };

  const t = (key: keyof Translations, params?: TranslateParams) => {
    const raw = translations[language][key] || translations.ru[key] || key;
    return interpolate(raw, params);
  };

  return (
    <LanguageContext.Provider value={{ language, setLanguage: handleSetLanguage, t }}>
      {children}
    </LanguageContext.Provider>
  );
};

export const useTranslation = () => useContext(LanguageContext);
